"""Builds the PDF/A text font (#116) into src/core/archiveFontData.ts.

PDF/A needs every font embedded, but marks, the watermark and page numbers are
set in the standard Helvetica, which isn't. In PDF/A exports they're set in
Arimo instead (Copyright 2020 The Arimo Project Authors, SIL Open Font License
1.1, no Reserved Font Name), which has Helvetica's widths for almost every
character, so the layout made with Helvetica's metrics still fits. Only the
Windows-1252 characters are kept, the set Helvetica writes, and the hinting is
dropped: about a fifth of the size.

Run (the font is the Regular TTF of the npm package):
  pip install fonttools
  npm pack @expo-google-fonts/arimo@0.4.3 && tar xzf expo-google-fonts-arimo-0.4.3.tgz
  python3 scripts/make-archive-font.py package/400Regular/Arimo_400Regular.ttf
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

NAME = "Arimo"
# Windows-1252 as PDF's WinAnsiEncoding: 32–255, without the five codes
# Windows leaves undefined (and DEL).
CODES = [c for c in range(32, 256) if c not in (0x7F, 0x81, 0x8D, 0x8F, 0x90, 0x9D)]
CHARS = {c: bytes([c]).decode("cp1252") for c in CODES}

source = TTFont(sys.argv[1])
options = subset.Options()
options.hinting = False
options.desubroutinize = True
options.layout_features = []  # one glyph per character: no kerning or ligatures in the PDF
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]  # keep the copyright and licence
options.notdef_outline = True
options.glyph_names = False
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=[ord(ch) for ch in CHARS.values()])
subsetter.subset(source)
source["head"].created = source["head"].modified = 0  # reproducible bytes

out = io.BytesIO()
source.save(out)
data = out.getvalue()

upm = source["head"].unitsPerEm
cmap = source.getBestCmap()
hmtx = source["hmtx"]
scale = lambda v: round(v * 1000 / upm)
widths = []
for code in range(32, 256):
    ch = CHARS.get(code)
    glyph = cmap.get(ord(ch)) if ch else None
    widths.append(scale(hmtx[glyph][0]) if glyph else 0)
missing = [ch for ch in CHARS.values() if ord(ch) not in cmap]
if missing:
    sys.exit(f"Arimo has no {missing}")

head, os2, post = source["head"], source["OS/2"], source["post"]
b64 = base64.b64encode(data).decode()
lines = [b64[i : i + 100] for i in range(0, len(b64), 100)]
target = Path(__file__).resolve().parent.parent / "src" / "core" / "archiveFontData.ts"
target.write_text(
    "// Generated by scripts/make-archive-font.py: don't edit.\n"
    "// Arimo Regular, Copyright 2020 The Arimo Project Authors\n"
    "// (https://github.com/googlefonts/arimo), SIL Open Font License 1.1\n"
    "// (licenses/arimo-OFL.txt), kept to Windows-1252.\n"
    f"export const ARCHIVE_FONT_NAME = '{NAME}'\n"
    "/** Advance widths (1/1000 em) of WinAnsi codes 32–255; 0 where Windows-1252 has no character. */\n"
    f"export const ARCHIVE_WIDTHS = [{', '.join(map(str, widths))}]\n"
    f"export const ARCHIVE_BBOX = [{scale(head.xMin)}, {scale(head.yMin)}, {scale(head.xMax)}, {scale(head.yMax)}]\n"
    f"export const ARCHIVE_ASCENT = {scale(os2.sTypoAscender)}\n"
    f"export const ARCHIVE_DESCENT = {scale(os2.sTypoDescender)}\n"
    f"export const ARCHIVE_CAP_HEIGHT = {scale(os2.sCapHeight)}\n"
    f"export const ARCHIVE_ITALIC_ANGLE = {post.italicAngle}\n"
    "export const ARCHIVE_TTF_BASE64 =\n"
    + "\n".join(f"  '{line}'{' +' if i < len(lines) - 1 else ''}" for i, line in enumerate(lines))
    + "\n"
)
print(f"{len(data)} bytes, {len(CODES)} characters → {target}")
