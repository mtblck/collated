"""Builds the text layer's glyphless font (#94) into src/core/glyphlessFont.ts.

OCR's invisible text (rendering mode 3) never shows, so its font needs no
shapes: empty glyphs (.notdef, one blank, and a zero-width one for combining
marks, #139) are enough to write every script. core/glyphless.ts maps each character it writes to the blank glyph and
names the character in a ToUnicode CMap, so search and copy read it back.

Run: pip install fonttools && python3 scripts/make-glyphless-font.py
The output is ours (MIT, like the rest of Collated); nothing is copied from
another font.
"""

import base64
import io
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

NAME = "CollatedGlyphless"
# Helvetica's ascent and descent, so selection boxes match the Helvetica words
# beside them (pdftotext and viewers box text by these).
ASCENT, DESCENT, ADVANCE = 718, -207, 500

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder([".notdef", "blank", "mark"])
fb.setupCharacterMap({})
empty = TTGlyphPen(None).glyph()
fb.setupGlyf({".notdef": empty, "blank": empty, "mark": empty})
fb.setupHorizontalMetrics({".notdef": (ADVANCE, 0), "blank": (ADVANCE, 0), "mark": (0, 0)})
fb.setupHorizontalHeader(ascent=ASCENT, descent=DESCENT)
fb.setupNameTable(
    {
        "familyName": NAME,
        "styleName": "Regular",
        "uniqueFontIdentifier": NAME,
        "fullName": NAME,
        "psName": NAME,
        "version": "Version 1.0",
    }
)
fb.setupOS2(
    sTypoAscender=ASCENT,
    sTypoDescender=DESCENT,
    usWinAscent=ASCENT,
    usWinDescent=-DESCENT,
    fsType=0,  # installable: no embedding restrictions
)
fb.setupPost()
fb.setupHead(created=0, modified=0)  # fixed, so the bytes are reproducible
fb.font["head"].created = fb.font["head"].modified = 0

out = io.BytesIO()
fb.save(out)
data = out.getvalue()
encoded = base64.b64encode(data).decode()

target = Path(__file__).resolve().parent.parent / "src" / "core" / "glyphlessFont.ts"
target.write_text(
    "// Generated by scripts/make-glyphless-font.py; don't edit.\n"
    "/** A TrueType font of empty glyphs: 1 is blank, 2 is a zero-width mark (see core/glyphless.ts). */\n"
    f"export const GLYPHLESS_TTF_BASE64 =\n  '{encoded}'\n"
    f"export const GLYPHLESS_ASCENT = {ASCENT}\n"
    f"export const GLYPHLESS_DESCENT = {DESCENT}\n"
    f"export const GLYPHLESS_ADVANCE = {ADVANCE}\n"
)
print(f"{len(data)} bytes -> {target}")
